"""Schema changes ship as Alembic migrations (RS-59, ADR 0008).

Runs on SQLite locally and on PostgreSQL in the `test-postgres` job, like the rest of the
integration suite.
"""

from collections.abc import Callable, Iterator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from fastapi.testclient import TestClient
from sqlalchemy import Engine, inspect, text

from app.core.db import build_engine, init_db
from app.llm.provider import LLMProvider
from app.llm.providers.fake import FakeLLMProvider

ALEMBIC_INI = Path(__file__).resolve().parents[2] / "alembic.ini"
TABLES = {"processes", "process_steps", "analyses", "recommendation_overrides"}


@pytest.fixture
def engine(database_url: str) -> Iterator[Engine]:
    engine = build_engine(database_url)
    _drop_version_table(engine)
    yield engine
    _drop_version_table(engine)
    engine.dispose()


@pytest.fixture
def alembic_config(database_url: str) -> Config:
    config = Config(str(ALEMBIC_INI))
    config.set_main_option("sqlalchemy.url", database_url)
    config.attributes["configure_logger"] = False
    return config


def _drop_version_table(engine: Engine) -> None:
    with engine.begin() as connection:
        connection.execute(text("DROP TABLE IF EXISTS alembic_version"))


def _current_revision(engine: Engine) -> str | None:
    with engine.connect() as connection:
        return MigrationContext.configure(connection).get_current_revision()


def _head(config: Config) -> str | None:
    return ScriptDirectory.from_config(config).get_current_head()


@pytest.mark.req("RS-59", criterion=1)
def test_upgrade_head_then_check_finds_no_pending_changes(
    engine: Engine, alembic_config: Config
) -> None:
    command.upgrade(alembic_config, "head")
    # check raises AutogenerateDiffsDetected when the models and the migrations disagree.
    command.check(alembic_config)

    assert set(inspect(engine).get_table_names()) >= TABLES
    assert _current_revision(engine) == _head(alembic_config)


@pytest.mark.req("RS-59", criterion=2)
def test_api_creates_no_table_when_schema_on_startup_is_off(
    engine: Engine,
    make_client: Callable[..., TestClient],
) -> None:
    make_client(FakeLLMProvider(), create_schema_on_startup=False)

    assert set(inspect(engine).get_table_names()) & TABLES == set()


@pytest.mark.req("RS-59")
def test_api_still_creates_tables_by_default(
    engine: Engine, make_client: Callable[[LLMProvider], TestClient]
) -> None:
    make_client(FakeLLMProvider())

    assert set(inspect(engine).get_table_names()) >= TABLES


@pytest.mark.req("RS-59", criterion=3)
def test_database_from_create_all_is_stamped_and_upgrade_applies_nothing(
    engine: Engine, alembic_config: Config
) -> None:
    init_db(engine)

    command.stamp(alembic_config, "head")
    # Any create_table left to apply would fail here, because the tables already exist.
    command.upgrade(alembic_config, "head")
    command.check(alembic_config)

    assert _current_revision(engine) == _head(alembic_config)


@pytest.mark.req("RS-59")
def test_downgrade_to_base_removes_every_table(engine: Engine, alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, "base")

    assert set(inspect(engine).get_table_names()) & TABLES == set()
